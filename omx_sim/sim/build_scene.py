"""Generate a MuJoCo workspace scene from a scene parameter file.

Writes (next to the ROBOTIS model, so the mesh paths resolve):
  mujoco/omx/omx_wrist.xml  = omx.xml + a "wrist" camera on end_effector_link
  mujoco/omx/<scene_file>   = robot + stand + box table + Pinky + boxes + "top" camera
Environments:
  calib/scene_params.json      -> workspace_scene.xml       (omx_1024_test_jihyeok_success; fits to the video:
      calibrate_top_camera.py, fit_workspace.py, fit_boxes.py, fit_wrist_camera.py; the user's tape
      measurements from memory are kept in workspace_scene_measured.xml)
  calib/scene_params_1027.json -> workspace_scene_1027.xml  (omx_1027_jihyeok_*; fit_env_1027.py)

  python -I sim/build_scene.py [--params sim/calib/scene_params_1027.json]
"""

import argparse
import json
from pathlib import Path

import numpy as np

SIM = Path(__file__).resolve().parent
OMX = SIM / "open_manipulator/open_manipulator_description/mujoco/omx"
PARAMS = SIM / "calib/scene_params.json"


def rot(yaw, pitch, roll):
    cz, sz, cy, sy, cx, sx = np.cos(yaw), np.sin(yaw), np.cos(pitch), np.sin(pitch), np.cos(roll), np.sin(roll)
    return (np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]) @ np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]])
            @ np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]]))


R0_TOP = np.array([[0, -1, 0], [1, 0, 0], [0, 0, 1]], float).T  # looking down, image up = +x


def xyaxes(R):
    return " ".join(f"{v:.6f}" for v in np.concatenate([R[:, 0], R[:, 1]]))


def f(v):
    return " ".join(f"{x:.4f}" for x in np.atleast_1d(v))


def write_wrist_model(wc):
    src = (OMX / "omx.xml").read_text()
    anchor = '<body name="end_effector_link" pos="0.09193 -0.0016 0">'
    assert anchor in src
    R = rot(*np.radians(wc["yaw_pitch_roll_deg"])) @ np.array(wc["base_axes"], float).T
    cam = (f'\n                  <camera name="wrist" mode="fixed" pos="{f(wc["pos_m"])}" xyaxes="{xyaxes(R)}" '
           f'fovy="{wc["fovy_deg"]:.3f}"/>')
    marker = '<geom size="0.005 0.005 0.005" type="box" contype="0" conaffinity="0" group="2"'
    assert src.count(marker) == 1
    src = src.replace(marker, marker.replace('group="2"', 'group="3"'))  # red tip marker sits in front of the lens
    (OMX / "omx_wrist.xml").write_text(src.replace(anchor, anchor + cam).replace('model="omx_f"', 'model="omx_f_wrist"'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--params", default=str(PARAMS))
    args = ap.parse_args()
    p = json.loads(Path(args.params).read_text())
    scene_file = p.get("scene_file", "workspace_scene.xml")
    stand = p.get("stand_size_m", [0.12, 0.12])  # x, y; centred on the robot base
    write_wrist_model(p["wrist_camera"])
    t, pk, tc, floor = p["table"], p["pinky"], p["top_camera"], p["floor_z"]
    R_top = rot(*np.radians(tc["yaw_pitch_roll_deg"])) @ R0_TOP
    tsize = [(t["x_far"] - t["x_near"]) / 2, (t["y_left"] - t["y_right"]) / 2, (t["top_z"] - floor) / 2]
    tpos = [(t["x_far"] + t["x_near"]) / 2, (t["y_left"] + t["y_right"]) / 2, (t["top_z"] + floor) / 2]
    body_top = pk["disk_top_z"] - 2 * pk["disk_half_height"]
    boxes = ""
    for name, b in p["boxes"].items():
        h = np.broadcast_to(np.asarray(b["size_m"], float), 3) / 2  # cube edge or [x, y, z]
        boxes += (f'    <body name="{name}" pos="{f(b["pos_m"])}" euler="0 0 {b["yaw_deg"]:.2f}">\n'
                  f'      <freejoint/>\n'
                  f'      <geom name="{name}" group="1" type="box" size="{f(h)}" mass="{b["mass_kg"]}" '
                  f'rgba="{f(b["rgba"])}" friction="1 0.01 0.001"/>\n    </body>\n')
    xml = f'''<mujoco model="omx workspace (box to Pinky)">
  <!-- GENERATED by sim/build_scene.py from sim/calib/{Path(args.params).name} - edit that, not this file.
       Frame: origin = bottom centre of the robot base (top of its stand), x = robot forward, y = robot left,
       z = up. Table / Pinky / cameras / box start positions fitted to the recorded top and wrist video;
       box size/mass and the stand height are the user's values. Workspace geoms are in group 1 so the arm
       can be rendered alone. -->
  <include file="omx_wrist.xml"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.4 0.4 0.4" specular="0 0 0"/>
    <global offwidth="640" offheight="480"/>
  </visual>

  <asset>
    <texture type="2d" name="carpet" builtin="checker" rgb1="0.35 0.35 0.37" rgb2="0.3 0.3 0.32" width="200" height="200"/>
    <material name="carpet" texture="carpet" texrepeat="20 20"/>
    <material name="white" rgba="0.92 0.92 0.92 1"/>
    <material name="pinky_body" rgba="0.15 0.15 0.15 1"/>
  </asset>

  <worldbody>
    <light pos="0 0 1.5" dir="0 0 -1" directional="true"/>
    <geom name="floor" group="1" type="plane" size="1 1 0.05" pos="0 0 {floor:.4f}" material="carpet"/>
    <geom name="robot_stand" group="1" type="box" size="{stand[0] / 2:.4f} {stand[1] / 2:.4f} {-floor / 2:.4f}" pos="0 0 {floor / 2:.4f}" rgba="{f(p.get("stand_rgba", [0.6, 0.45, 0.3, 1]))}"/>
    <geom name="table" group="1" type="box" size="{f(tsize)}" pos="{f(tpos)}" material="white"/>
    <body name="pinky" pos="{pk["x"]:.4f} {pk["y"]:.4f} 0" euler="0 0 {pk.get("yaw_deg", 0.0):.2f}">
      <geom name="pinky_body" group="1" type="box" size="{f([pk["body_size_m"][0] / 2, pk["body_size_m"][1] / 2, (body_top - floor) / 2])}"
        pos="0 0 {(body_top + floor) / 2:.4f}" material="pinky_body"/>
      <geom name="pinky_disk" group="1" type="cylinder" size="{pk["disk_radius"]:.4f} {pk["disk_half_height"]:.4f}"
        pos="0 0 {pk["disk_top_z"] - pk["disk_half_height"]:.4f}" material="white"/>
    </body>
{boxes}    <camera name="top" mode="fixed" pos="{f(tc["pos_m"])}" xyaxes="{xyaxes(R_top)}" fovy="{tc["fovy_deg"]:.3f}"/>
  </worldbody>
</mujoco>
'''
    (OMX / scene_file).write_text(xml)
    print("wrote", OMX / scene_file, "and omx_wrist.xml")


if __name__ == "__main__":
    main()
